"""Render resolved build dependencies as a requirements file.

The layout follows what pip-compile wrote when pybuild-deps used pip-tools,
so regenerating an existing file only changes what actually changed.
"""

from __future__ import annotations

import shlex
import sys
from collections.abc import Iterable, Iterator
from dataclasses import dataclass, field

from packaging.utils import canonicalize_name
from packaging.version import InvalidVersion, Version

from pybuild_deps.compile_build_dependencies import ResolvedDependency


DEFAULT_INDEX_URL = "https://pypi.org/simple"
# Packages pip-tools listed in a separate section of the file.
UNSAFE_PACKAGES = frozenset({"setuptools", "distribute", "pip"})
MESSAGE_UNSAFE_PACKAGES = (
    "# The following packages are considered to be unsafe in a requirements file:"
)


def render(
    results: Iterable[ResolvedDependency],
    *,
    compile_command: str | None,
    options: list[str],
    annotate: bool,
    annotation_style: str,
    generate_hashes: bool,
) -> str:
    """Return the requirements file contents. No header when compile_command is None."""
    lines: list[str] = []
    if compile_command is not None:
        lines.extend(
            [
                "#",
                (
                    "# This file is autogenerated by pybuild-deps with Python "
                    f"{sys.version_info.major}.{sys.version_info.minor}"
                ),
                "# by the following command:",
                "#",
                f"#    {compile_command}",
                "#",
            ]
        )
    flags = list(format_options(options))
    if flags:
        lines.extend([*flags, ""])

    results = sorted(results, key=_sort_key)
    format_dep = _Formatter(annotate, annotation_style, generate_hashes)
    lines.extend(format_dep(r) for r in results if r.name not in UNSAFE_PACKAGES)
    unsafe = [format_dep(r) for r in results if r.name in UNSAFE_PACKAGES]
    if unsafe:
        lines.extend(["", MESSAGE_UNSAFE_PACKAGES, *unsafe])
    return "\n".join(lines) + "\n"


def _sort_key(dep: ResolvedDependency) -> tuple[str, bool, Version | str]:
    try:
        return canonicalize_name(dep.name), False, Version(dep.version)
    except InvalidVersion:
        return canonicalize_name(dep.name), True, dep.version


class _Formatter:
    def __init__(self, annotate: bool, annotation_style: str, generate_hashes: bool):
        self.annotate = annotate
        self.annotation_style = annotation_style
        self.generate_hashes = generate_hashes

    def __call__(self, dep: ResolvedDependency) -> str:
        if dep.url:
            line = f"{canonicalize_name(dep.name)} @ {dep.url}"
        else:
            line = f"{canonicalize_name(dep.name)}=={dep.version}"
        if dep.marker:
            line += f" ; {dep.marker}"
        hashes = sorted(dep.hashes) if self.generate_hashes else []
        for hash_ in hashes:
            line += f" \\\n    --hash={hash_}"
        if not self.annotate or not dep.via:
            return line
        via = sorted(dep.via)
        if self.annotation_style == "line":
            annotation = f"# via {', '.join(via)}"
            sep = "\n    " if hashes else "  "
        elif len(via) == 1:
            annotation = f"# via {via[0]}"
            sep = "\n    "
        else:
            annotation = "\n    ".join(["# via", *(f"#   {v}" for v in via)])
            sep = "\n    "
        # 24 is the column pip-compile aligned single line annotations to
        lines = f"{line:24}{sep}{annotation}".splitlines()
        return "\n".join(ln.rstrip() for ln in lines)


@dataclass
class _PipOptions:
    """The pip options pip-compile recorded, gathered like pip does."""

    index_url: str = DEFAULT_INDEX_URL
    extra_index_urls: list[str] = field(default_factory=list)
    find_links: list[str] = field(default_factory=list)
    trusted_hosts: list[str] = field(default_factory=list)
    no_index: bool = False
    no_binary: set[str] = field(default_factory=set)
    only_binary: set[str] = field(default_factory=set)

    def apply(self, name: str, value: str) -> None:
        if name in ("-i", "--index-url"):
            self.index_url = value
        elif name == "--extra-index-url":
            self.extra_index_urls.append(value)
        elif name in ("-f", "--find-links"):
            self.find_links.append(value)
        elif name == "--trusted-host":
            self.trusted_hosts.append(value)
        elif name == "--no-index":
            self.no_index = True
        elif name == "--no-binary":
            _handle_format_control(value, self.no_binary, self.only_binary)
        elif name == "--only-binary":
            _handle_format_control(value, self.only_binary, self.no_binary)


def format_options(options: Iterable[str]) -> Iterator[str]:
    """Yield the pip options worth recording in the output, as pip-compile did.

    Index URLs (the first one only when it isn't PyPI), find-links, trusted
    hosts and binary format controls. Options that don't affect which files
    get installed, like --pre, are left out.
    """
    pip = _PipOptions()
    for name, value in _split_options(options):
        pip.apply(name, value)

    index_urls = [] if pip.no_index else _dedup([pip.index_url, *pip.extra_index_urls])
    for i, url in enumerate(index_urls):
        if i == 0 and url.rstrip("/") == DEFAULT_INDEX_URL:
            continue
        yield f"{'--index-url' if i == 0 else '--extra-index-url'} {url}"
    yield from (f"--find-links {link}" for link in _dedup(pip.find_links))
    yield from (f"--trusted-host {host}" for host in _dedup(pip.trusted_hosts))
    # :all: first, then package names, preserving pip's precedence rules
    controls = (("--no-binary", pip.no_binary), ("--only-binary", pip.only_binary))
    yield from (f"{flag} :all:" for flag, names in controls if ":all:" in names)
    for flag, names in controls:
        yield from (f"{flag} {name}" for name in sorted(names - {":all:"}))


def _split_options(options: Iterable[str]) -> Iterator[tuple[str, str]]:
    for option in options:
        name, *rest = shlex.split(option)
        name, eq, value = name.partition("=")
        if not eq:
            value = rest[0] if rest else ""
        yield name, value


def _handle_format_control(value: str, target: set[str], other: set[str]) -> None:
    """Apply --no-binary/--only-binary like pip's FormatControl."""
    new = value.split(",")
    while ":all:" in new:
        other.clear()
        target.clear()
        target.add(":all:")
        del new[: new.index(":all:") + 1]
        if ":none:" not in new:
            return
    for name in new:
        if name == ":none:":
            target.clear()
            continue
        name = canonicalize_name(name)
        other.discard(name)
        target.add(name)


def _dedup(items: Iterable[str]) -> list[str]:
    return list(dict.fromkeys(items))
